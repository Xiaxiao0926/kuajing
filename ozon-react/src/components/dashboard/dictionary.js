export const R = 0.09

export const fmtCNY = (v) => {
  const cny = v * R
  if (cny >= 10000) return `${(cny / 10000).toFixed(1)}万`
  if (cny >= 1000) return `${(cny / 1000).toFixed(1)}K`
  return cny?.toFixed(0) || 0
}

export const fmtCNYFull = (v) => {
  const cny = Math.round(v * R)
  return cny.toLocaleString()
}

